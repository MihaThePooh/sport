#!/usr/bin/env python3
"""Проверки дневника: формат записи и совместимость со старым файлом.

Запуск:

    python3 test_server.py

Пишет во временную папку, боевой дневник не трогает. Проверяется не
«работает ли сервер вообще», а те два места, где легко сломать данные:
разбор старого CSV без колонки «формат» и запись новой.
"""
import os
import sys
import tempfile
from pathlib import Path

TMP = Path(tempfile.mkdtemp(prefix="sport-test-"))
os.environ["SPORT_DATA"] = str(TMP)

sys.path.insert(0, str(Path(__file__).resolve().parent))
import server                                            # noqa: E402

HOME = TMP
ok = 0


def проверка(имя, условие, что=""):
    """Провал останавливает прогон сразу: дальше всё равно поедет по
    испорченным данным, и второй провал уже ничего не скажет."""
    global ok
    if условие:
        ok += 1
        print("ок:", имя)
    else:
        print("ПРОВАЛ:", имя, что)
        sys.exit(1)


# --- 1. Старый файл без колонки «формат» читается как обычные тренировки ---
HOME.mkdir(parents=True, exist_ok=True)
(HOME / "log.csv").write_text(
    "дата,упражнение,подходы,всего\n"
    "2026-01-15,подтягивания,10 8 6,24\n"
    "2026-01-16,отжимания,,40\n",
    encoding="utf-8")

rows = server.read(HOME)
проверка("старый файл читается", len(rows) == 2, rows)
проверка("формат у старых записей пустой",
         all(r["формат"] == server.NORMAL for r in rows), rows)
проверка("день без подходов не потерян",
         server.total_of(rows[1]) == 40, rows[1])

# --- 2. Обычная запись ---
server.add(HOME, "подтягивания", [10, 8, 7], "2026-09-10")
last = [r for r in server.read(HOME) if r["дата"] == "2026-09-10"][0]
проверка("обычная запись без пометки", last["формат"] == server.NORMAL, last)
# «всего» лежит в файле строкой — это CSV, тут всё строки
проверка("сумма посчитана", server.total_of(last) == 25, last)

# --- 3. Мио-серия ---
server.add(HOME, "подтягивания", [10, 4, 4, 3, 3], "2026-09-11", server.MYO)
myo = [r for r in server.read(HOME) if r["дата"] == "2026-09-11"][0]
проверка("мио-серия помечена", myo["формат"] == server.MYO, myo)
проверка("круги записаны как есть", myo["подходы"] == "10 4 4 3 3", myo)

# --- 4. Старые записи от новой записи не пострадали ---
старая = [r for r in server.read(HOME) if r["дата"] == "2026-01-15"][0]
проверка("старая запись цела",
         старая["подходы"] == "10 8 6" and старая["формат"] == server.NORMAL,
         старая)

# --- 5. Отказы ---
def отказ(*args, **kw):
    try:
        server.add(HOME, *args, **kw)
    except ValueError:
        return True
    return False


проверка("мио из одного числа не принимается",
         отказ("подтягивания", [10], "2026-09-12", server.MYO))
проверка("выдуманный формат не принимается",
         отказ("подтягивания", [10, 5], "2026-09-12", "секретный"))
проверка("дробные повторения не принимаются",
         отказ("подтягивания", [10.5], "2026-09-12"))

# --- 6. Состояние знает формат последнего занятия ---
st = server.state(HOME)
последнее = st["движения"]["подтягивания"]["последнее"]
проверка("состояние отдаёт формат", последнее["формат"] == server.MYO, последнее)
проверка("рекорд за год считается по всем форматам",
         st["движения"]["подтягивания"]["рекорд"]["подход"] >= 10, st)

# --- 7. Несколько серий за один день ---
#
# Ради этого всё и затевалось: две мио-серии подтягиваний — одно
# занятие, а не две записи. Раньше вторая молча затирала первую.
server.add(HOME, "подтягивания", [[9, 3, 3, 3], [5, 2, 2]],
           "2026-09-20", server.MYO, "тяжело шли")
запись = [r for r in server.read(HOME)
          if r["дата"] == "2026-09-20" and r["упражнение"] == "подтягивания"][0]

проверка("серии разделены в файле",
         запись["подходы"] == "9 3 3 3 \\ 5 2 2", запись["подходы"])
проверка("серии читаются обратно",
         server.series_of(запись) == [[9, 3, 3, 3], [5, 2, 2]], запись)
проверка("сумма считается по всем сериям",
         server.total_of(запись) == 27, запись)
проверка("рекорд видит лучший подход любой серии",
         max(server.sets_of(запись)) == 9, запись)
проверка("комментарий сохранён", server.note_of(запись) == "тяжело шли", запись)
проверка("старая запись — это одна серия",
         server.series_of({"подходы": "12 11 9"}) == [[12, 11, 9]])
проверка("слишком много серий не принимается",
         отказ("подтягивания", [[2]] * 9, "2026-09-20"))
# Перевод строки внутри комментария разорвал бы CSV на чтении: строка
# файла и строка данных перестали бы совпадать.
server.add(HOME, "отжимания", [20], "2026-09-20", server.NORMAL, "болит\nплечо")
отжимания = [r for r in server.read(HOME)
             if r["дата"] == "2026-09-20" and r["упражнение"] == "отжимания"][0]
проверка("комментарий в одну строку",
         server.note_of(отжимания) == "болит плечо", отжимания)

# --- 8. Дописывание серий: обе кнопки записи кладут серию рядом ---
#
# Главный сценарий новой формы: сделал серию — записал, поля очистились,
# сделал вторую — записал. Вторая не должна затирать первую.
server.add(HOME, "приседания", [40, 30], "2026-09-21", server.NORMAL, "", True)
server.add(HOME, "приседания", [20, 20], "2026-09-21", server.NORMAL, "", True)
присед = [r for r in server.read(HOME)
          if r["дата"] == "2026-09-21" and r["упражнение"] == "приседания"][0]

проверка("вторая серия дописалась",
         server.series_of(присед) == [[40, 30], [20, 20]], присед)
проверка("сумма выросла на вторую серию",
         server.total_of(присед) == 110, присед)

# Без флага «дописать» запись дня заменяется целиком — это правка.
server.add(HOME, "приседания", [50], "2026-09-21")
присед = [r for r in server.read(HOME)
          if r["дата"] == "2026-09-21" and r["упражнение"] == "приседания"][0]
проверка("правка заменяет день целиком",
         server.series_of(присед) == [[50]], присед)

# --- 9. Пометка «мио» ставится сама, но чужой текст не трогает ---
server.add(HOME, "подтягивания", [9, 3, 3], "2026-09-22", server.MYO, "", True)
тяга = [r for r in server.read(HOME)
        if r["дата"] == "2026-09-22" and r["упражнение"] == "подтягивания"][0]
проверка("мио пометила себя в комментарии",
         server.note_of(тяга) == "мио-серии", тяга)

server.note_set(HOME, "подтягивания", "2026-09-22", "мио, пятая тяжело")
server.add(HOME, "подтягивания", [8, 3, 3], "2026-09-22", server.MYO, "", True)
тяга = [r for r in server.read(HOME)
        if r["дата"] == "2026-09-22" and r["упражнение"] == "подтягивания"][0]
проверка("свой комментарий не затёрт записью серии",
         server.note_of(тяга) == "мио, пятая тяжело", тяга)
проверка("обе серии на месте",
         server.series_of(тяга) == [[9, 3, 3], [8, 3, 3]], тяга)

# --- 10. Комментарий правится отдельно от подходов ---
server.note_set(HOME, "подтягивания", "2026-09-22", "мио, добавил шестую")
тяга = [r for r in server.read(HOME)
        if r["дата"] == "2026-09-22" and r["упражнение"] == "подтягивания"][0]
проверка("комментарий переписан", server.note_of(тяга) == "мио, добавил шестую")
проверка("подходы не пострадали",
         server.series_of(тяга) == [[9, 3, 3], [8, 3, 3]], тяга)

# Слеш в тексте разорвал бы разбор серий и склейку комментариев дня.
server.note_set(HOME, "подтягивания", "2026-09-22", "тяжело \\ но сделал")
тяга = [r for r in server.read(HOME)
        if r["дата"] == "2026-09-22" and r["упражнение"] == "подтягивания"][0]
проверка("слеш из комментария убран",
         "\\" not in server.note_of(тяга), server.note_of(тяга))

# --- 11. Таблица дня для формы ---
дни = server.state(HOME)["дни"]
проверка("таблица отдаёт не больше пятнадцати дней", len(дни) <= 15, len(дни))
последний = дни[-1]
проверка("в дне видно серии",
         последний["движения"]["подтягивания"]["серии"] == [[9, 3, 3], [8, 3, 3]],
         последний)
проверка("комментарий дня с именем движения",
         последний["комментарий"].startswith("подтягивания: "), последний)

print("\nвсего проверок:", ok, "— провалов нет")
